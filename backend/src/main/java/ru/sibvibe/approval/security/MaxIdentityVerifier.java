package ru.sibvibe.approval.security;

import java.util.Optional;

/**
 * Проверка подлинности личности пользователя, пришедшей из мини-приложения.
 *
 * MAX Bridge отдаёт фронтенду данные запуска с подписью. Фронтенд — браузер пользователя, всё, что он присылает,
 * можно подделать: идентификатор из тела запроса без проверки подписи позволил бы действовать от имени любого
 * участника. Поэтому идентификатор берётся только из проверенных данных запуска, никогда из параметров или тела
 * запроса.
 *
 * Подпись проверяется секретом бота; дополнительно проверяется давность выдачи, иначе перехваченные данные
 * действовали бы бессрочно.
 */
public interface MaxIdentityVerifier {

    /**
     * @param rawInitData строка данных запуска, как её отдал MAX Bridge
     * @return личность, если подпись верна и данные не просрочены; иначе пусто
     * @throws InitDataExpiredException если подпись верна, но данные просрочены
     */
    Optional<VerifiedIdentity> verify(String rawInitData);

    /**
     * @param maxUserId  идентификатор пользователя в MAX - единственный доверенный
     *                   ключ для поиска пользователя в нашей базе
     * @param startParam параметр ссылки вида max.ru/бот?startapp=... - например,
     *                   токен приглашения в компанию. Берётся только отсюда, из
     *                   проверенной строки, а не из initDataUnsafe на фронтенде.
     *                   null, если приложение открыто без параметра
     */
    record VerifiedIdentity(
            String maxUserId,
            String displayName,
            long issuedAtEpochSeconds,
            String startParam
    ) {}
}
