/**
 * Название компании в тексте: «Ромашка», а «ООО «Ромашка»» — как есть, без кавычек в кавычках.
 * Слово «компания» перед названием держит падеж: «в компанию «Ромашка»», а не «в Ромашка».
 */
export function orgInText(name: string): string {
  return /[«»"„“]/.test(name) ? name : `«${name}»`;
}
